export function legalMetadata(slug: string): Metadata {
  const doc = LEGAL_DOCS[slug];
  return {
    title: doc.title,
    description: doc.description,
    alternates: pageAlternates(`/${doc.slug}`),
  };
}

export function LegalPage({ slug }: { slug: string }) {
  const doc = LEGAL_DOCS[slug];
  return (
    <Container className="py-6 md:py-10">
      <Breadcrumbs items={[{ title: doc.title, href: `/${doc.slug}` }]} />
      <article className="mx-auto mt-8 max-w-2xl">
        <h1 className="font-display text-display-sm font-light md:text-display">{doc.title}</h1>
        <p className="mt-2 text-[12px] text-muted">
          Редакція від{" "}
          {new Date(doc.updated).toLocaleDateString("uk-UA", { day: "numeric", month: "long", year: "numeric" })}
        </p>
        <div className="mt-8 space-y-8">
          {doc.sections.map((s) => (
            <section key={s.h}>
              <h2 className="text-[15px] font-medium">{s.h}</h2>
              <div className="mt-2.5 space-y-2.5 text-[13.5px] leading-relaxed text-muted">
                {s.p.map((par, i) => (
                  <p key={i}>{par}</p>
                ))}
              </div>
            </section>
          ))}
        </div>
      </article>
    </Container>
  );
}
